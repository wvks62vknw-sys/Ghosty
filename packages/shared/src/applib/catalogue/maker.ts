/** The sRGB channel (0 to 255) as linear light, the WCAG 2.2 relative luminance step. */
const lin = (v: string): string => `if(${v} / 255 <= 0.04045, ${v} / 255 / 12.92, pow((${v} / 255 + 0.055) / 1.055, 2.4))`;
/** WCAG relative luminance of an sRGB colour given by three input ids. */
const lum = (r: string, g: string, b: string): string => `0.2126 * ${lin(r)} + 0.7152 * ${lin(g)} + 0.0722 * ${lin(b)}`;

