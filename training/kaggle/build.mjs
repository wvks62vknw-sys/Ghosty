// Builds what the brain hands to Kaggle each week into apps/edge/src/selftrain/assets.ts:
//   TASKS_JS    — the GYM's puzzles and the drills as one node program (tasks-cli.js bundled), so the
//                 notebook makes and checks puzzles with exactly the code the phone uses;
//   TASKS_FILE  — its base64, size and SHA-256, worked out here so the brain spends no CPU on them when it
//                 uploads it (and knows from the hash whether it changed since the last upload);
//   NOTEBOOK_PY — training/kaggle/ghosty_weekly.py, the notebook the brain pushes to Kaggle.
// Run after changing either (or the games/drills):  node training/kaggle/build.mjs
// `--check` only says whether assets.ts is up to date (the edge tests run it that way).
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';

const at = (p) => new URL(p, import.meta.url).pathname;
const require = createRequire(at('../../apps/edge/package.json'));
const { build } = require('esbuild');

/** The node program alone (training/kaggle/test_ghosty_weekly.py runs it): `node build.mjs --tasks <file>`. */
export async function tasksJs() {
  const out = await build({
    entryPoints: [at('./tasks-cli.js')],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    minify: true,
    write: false,
    legalComments: 'none',
    logLevel: 'warning',
  });
  return out.outputFiles[0].text;
}

export async function assetsSource() {
  const js = await tasksJs();
  const py = readFileSync(at('./ghosty_weekly.py'), 'utf8');
  // One puzzle per game and level as seed text for Evol-Instruct (the brain cannot run the GYM itself).
  const dir = mkdtempSync(join(tmpdir(), 'ghosty-tasks-'));
  writeFileSync(join(dir, 'tasks.mjs'), js);
  const { handle } = await import(join(dir, 'tasks.mjs'));
  const reportCard = handle({ op: 'reportcard' }).texts;
  rmSync(dir, { recursive: true, force: true });
  const seeds = [];
  for (const game of handle({ op: 'games' }).games)
    for (let level = 1; level <= 10; level++) {
      const prompt = handle({ op: 'make', task: { game, level, seed: 800_000 + level } }).prompt;
      if (prompt && prompt.length <= 1600) seeds.push({ game, level, prompt });
    }
  return (
    '// GENERATED by training/kaggle/build.mjs: do not edit. Run `node training/kaggle/build.mjs` after changing\n' +
    '// training/kaggle/ghosty_weekly.py, training/kaggle/tasks-cli.js, the GYM games or the drills.\n' +
    '/** The GYM puzzles and drills as a node program for the notebook (tasks-cli.js, bundled). */\n' +
    `export const TASKS_JS = ${JSON.stringify(js)};\n` +
    '/** TASKS_JS as uploaded: its UTF-8 bytes in base64, their number and their SHA-256 (hex). */\n' +
    `export const TASKS_FILE = ${JSON.stringify({ b64: Buffer.from(js, 'utf8').toString('base64'), size: Buffer.byteLength(js, 'utf8'), sha256: createHash('sha256').update(js, 'utf8').digest('hex') })};\n` +
    '/** The weekly Kaggle notebook (training/kaggle/ghosty_weekly.py). */\n' +
    `export const NOTEBOOK_PY = ${JSON.stringify(py)};\n` +
    '/** One GYM puzzle per game and level (seed 800000 + level), the seed texts Evol-Instruct rewrites. */\n' +
    `export const GYM_SEEDS: { game: string; level: number; prompt: string }[] = ${JSON.stringify(seeds)};\n` +
    "/** The phone's REPORT CARD questions word for word (apps/web/src/gym/bench.ts reportCardTexts): never trained on. */\n" +
    `export const REPORT_CARD_TEXTS: string[] = ${JSON.stringify(reportCard)};\n`
  );
}

const target = at('../../apps/edge/src/selftrain/assets.ts');
if (process.argv[1] && process.argv[1].endsWith('build.mjs') && process.argv.includes('--tasks')) {
  writeFileSync(process.argv[process.argv.indexOf('--tasks') + 1], await tasksJs());
} else if (process.argv[1] && process.argv[1].endsWith('build.mjs')) {
  const src = await assetsSource();
  if (process.argv.includes('--check')) {
    let now = '';
    try {
      now = readFileSync(target, 'utf8');
    } catch {}
    if (now !== src) {
      console.error('apps/edge/src/selftrain/assets.ts is stale: run node training/kaggle/build.mjs');
      process.exit(1);
    }
    console.log('assets.ts is up to date');
  } else {
    writeFileSync(target, src);
    console.log(`wrote ${target} (${Math.round(src.length / 1024)} KB)`);
  }
}
